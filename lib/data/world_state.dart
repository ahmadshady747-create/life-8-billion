// حالة العالم المستمرة عبر الحياة كلها.
// ليست حدثا عابرا ينتهي، بل مناخ اقتصادي وتقني يبقى سنوات ثم ينقلب:
// ازدهار يرفع الرواتب والأسعار معا، وكساد يضرب الرواتب أولا، وتعافٍ
// بينهما، وركود يخنق ببطء. هذه سيناريوهات محاكاة مستوحاة من اتجاهات
// عامة، ليست بيانات رسمية ولا تنبؤات.

/// المراحل الاقتصادية الممكنة، بالترتيب من الأسوأ إلى الأفضل للرواتب.
const worldEconomies = ['كساد', 'ركود', 'تعافٍ', 'ازدهار'];

/// العصور التقنية الممكنة.
const worldTechs = ['عصر رقمي', 'ثورة ذكاء', 'عصر فضاء', 'ثورة خضراء'];

/// مضاعف الراتب في كل مرحلة: الكساد يضرب الدخل بقوة، والازدهار يرفعه.
double worldSalaryMultiplier(String economy) {
  switch (economy) {
    case 'ازدهار':
      return 1.15;
    case 'تعافٍ':
      return 1.05;
    case 'ركود':
      return 0.90;
    case 'كساد':
      return 0.75;
    default:
      return 1.0;
  }
}

/// مضاعف المصاريف في كل مرحلة: الازدهار يرفع الأسعار، والكساد يخفضها
/// قليلا لكنه لا يعوّض ضربة الراتب — وهذا هو الفخ الواقعي.
double worldExpenseMultiplier(String economy) {
  switch (economy) {
    case 'ازدهار':
      return 1.10;
    case 'تعافٍ':
      return 1.0;
    case 'ركود':
      return 0.95;
    case 'كساد':
      return 0.90;
    default:
      return 1.0;
  }
}

