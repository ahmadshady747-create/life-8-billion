import '../models.dart';
import 'events.dart';

/// سنوات التدبير: بين كل حدث مصيري وآخر، تمر سنة تدير فيها وقتك بنفسك.
/// هذه ليست أحداثا عشوائية، بل قرارا متكررا يشكّل شخصيتك ببطء:
/// من يدرس كل سنة يصبح مختلفا عمن يقضيها في الراحة.
LifeEvent yearlyEventForAge(int age) {
  if (age < 30) {
    return e('yearly_youth', age, age, '🗓️ سنة من حياتك: كيف تقضيها؟',
        'سنة عادية، لا حدث مصيري فيها. لكن السنوات العادية هي التي تصنعك: ما ستفعله كل يوم هو ما ستصبح عليه.',
        [
          c('أدرس وأطوّر مهاراتي', 'سنة من التعلم الهادئ، ومهاراتك تنمو بصمت.',
              const Effect(smarts: 8, skill: 8, happiness: -2), jump: 1),
          c('أعمل وأدخر', 'سنة من العمل والادخار، ورصيدك يكبر قليلا.',
              const Effect(money: 8, happiness: -2), cash: 3000, jump: 1),
          c('أقضيها مع أصدقائي وعائلتي', 'سنة مليئة بالناس، وعلاقاتك تتعمق.',
              const Effect(social: 10, happiness: 8, money: -2), jump: 1),
          c('أهتم بصحتي ورياضتي', 'سنة من الانضباط، وجسدك يشكرك.',
              const Effect(health: 10, happiness: 4), jump: 1),
          c('أسترخي وأستمتع بالحاضر', 'سنة خفيفة جميلة، دون تقدم يذكر.',
              const Effect(happiness: 10, smarts: -2), jump: 1),
        ]);
  }
  if (age < 65) {
    return e('yearly_adult', age, age, '🗓️ سنة من حياتك: كيف تقضيها؟',
        'سنة من المسؤوليات: عمل، بيت، وأشخاص يعتمدون عليك. كيف توزع وقتك هذه السنة؟',
        [
          c('أركز على عملي وترقيتي', 'سنة من الجهد، ومهنتك تتقدم.',
              const Effect(money: 10, skill: 6, health: -4), cash: 5000, jump: 1),
          c('أستثمر في تعلم جديد', 'سنة من التعلم المتأخر، ومهاراتك تتجدد.',
              const Effect(smarts: 8, skill: 10, money: -2), jump: 1),
          c('أعطي عائلتي الأولوية', 'سنة مع من تحب، وعلاقاتك تصبح أعمق.',
              const Effect(social: 10, happiness: 10, money: -2), jump: 1),
          c('أعتني بصحتي قبل فوات الأوان', 'سنة من الفحوصات والرياضة، وجسدك أقوى.',
              const Effect(health: 12, happiness: 2), jump: 1),
          c('أعيش لنفسي قليلا', 'سنة من السفر والهوايات، وروحك تتجدد.',
              const Effect(happiness: 12, money: -4), jump: 1),
        ]);
  }
  return e('yearly_old', age, age, '🗓️ سنة من حياتك: كيف تقضيها؟',
      'سنة هادئة في خريف العمر. الوقت صار أثمن، وكل سنة لها وزنها.',
      [
        c('أقضيها مع أحفادي وعائلتي', 'سنة دافئة، وذكريات جديدة لأحفادك.',
            const Effect(social: 12, happiness: 12), jump: 1),
        c('أكتب مذكراتي وأنقل خبرتي', 'سنة من التأمل والكتابة، وعقلك ما زال حادا.',
            const Effect(smarts: 8, happiness: 6, reputation: 4), jump: 1),
        c('أهتم بصحتي بصرامة', 'سنة من العلاج والرياضة الخفيفة، وجسدك يصمد.',
            const Effect(health: 12), jump: 1),
        c('أستريح تماما', 'سنة من الراحة، دون ضغط ولا التزامات.',
            const Effect(happiness: 8, health: -2), jump: 1),
      ]);
}
